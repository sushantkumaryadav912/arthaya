import type { ReportSummary, ResearchReport } from "@/lib/types";
import { UNIVERSE, findSeed } from "./stocks";
import { buildCompletedRun } from "./analysis";
import { isoDaysAgo, mulberry32, seedFrom } from "./generators";

export function buildReportSummaryForTicker(tickerInput: string): ReportSummary {
  const ticker = tickerInput.trim().toUpperCase();
  const seed = findSeed(ticker);
  const run = buildCompletedRun(seed.ticker)!;
  return {
    id: `rep_${seed.ticker.toLowerCase()}`,
    ticker: seed.ticker,
    company: seed.name,
    generatedAt: isoDaysAgo(0),
    horizonDays: run.horizonDays,
    model: run.prediction!.model,
    probability: run.prediction!.probability,
    overallSignal: run.summary!.overallSignal,
    agentStatus: "completed",
  };
}

export function buildReportSummaries(): ReportSummary[] {
  return UNIVERSE.map((s, i) => {
    const run = buildCompletedRun(s.ticker)!;
    return {
      id: `rep_${s.ticker.toLowerCase()}`,
      ticker: s.ticker,
      company: s.name,
      generatedAt: isoDaysAgo(i % 5),
      horizonDays: run.horizonDays,
      model: run.prediction!.model,
      probability: run.prediction!.probability,
      overallSignal: run.summary!.overallSignal,
      agentStatus: "completed",
    };
  });
}

export function buildReport(id: string): ResearchReport | null {
  const decoded = decodeURIComponent(id);
  const ticker = decoded.replace(/^rep_/, "").toUpperCase();
  const seed = findSeed(ticker);
  if (!seed) return null;
  const run = buildCompletedRun(seed.ticker)!;
  const rand = mulberry32(seedFrom(decoded));
  return {
    id: decoded,
    ticker: seed.ticker,
    company: seed.name,
    generatedAt: isoDaysAgo(Math.floor(rand() * 5)),
    horizonDays: run.horizonDays,
    model: run.prediction!.model,
    probability: run.prediction!.probability,
    overallSignal: run.summary!.overallSignal,
    agentStatus: "completed",
    executiveSummary: `${seed.name} (${seed.ticker}) research report generated by the Arthaya multi-agent pipeline over a ${run.horizonDays}-trading-day horizon. Model probability ${Math.round(run.prediction!.probability * 100)}% ${run.summary!.overallSignal}. Probabilistic estimate — not investment advice. Live pipeline: Quant ML Ensemble + Model Gateway.`,
    prediction: run.prediction!,
    critic: run.critic!,
    analysis: run.summary!,
    sources: [
      { provider: "yfinance (Market Data & OHLCV)", url: "#", retrievedAt: isoDaysAgo(0) },
      { provider: "SEC EDGAR (10-K & 10-Q Filings)", url: "#", retrievedAt: isoDaysAgo(1) },
      { provider: "n8n Orchestrator (Multi-Agent Grid)", url: "#", retrievedAt: isoDaysAgo(0) },
      { provider: "Firecrawl & Apify (Financial News Intelligence)", url: "#", retrievedAt: isoDaysAgo(0) },
    ],
  };
}
