import type { ReportSummary, ResearchReport } from "@/lib/types";
import { UNIVERSE, findSeed } from "./stocks";
import { buildCompletedRun } from "./analysis";
import { isoDaysAgo, mulberry32, seedFrom } from "./generators";

export function buildReportSummaries(): ReportSummary[] {
  return UNIVERSE.slice(0, 6).map((s, i) => {
    const run = buildCompletedRun(s.ticker)!;
    return {
      id: `rep_${s.ticker.toLowerCase()}`,
      ticker: s.ticker,
      company: s.name,
      generatedAt: isoDaysAgo(i),
      horizonDays: run.horizonDays,
      model: run.prediction!.model,
      probability: run.prediction!.probability,
      overallSignal: run.summary!.overallSignal,
      agentStatus: "completed",
    };
  });
}

export function buildReport(id: string): ResearchReport | null {
  const ticker = id.replace(/^rep_/, "").toUpperCase();
  const seed = findSeed(ticker);
  if (!seed) return null;
  const run = buildCompletedRun(ticker)!;
  const rand = mulberry32(seedFrom(id));
  return {
    id,
    ticker: seed.ticker,
    company: seed.name,
    generatedAt: isoDaysAgo(Math.floor(rand() * 5)),
    horizonDays: run.horizonDays,
    model: run.prediction!.model,
    probability: run.prediction!.probability,
    overallSignal: run.summary!.overallSignal,
    agentStatus: "completed",
    executiveSummary: `${seed.name} (${seed.ticker}) research report generated by the Arthaya multi-agent pipeline over a ${run.horizonDays}-trading-day horizon. Model probability ${Math.round(run.prediction!.probability * 100)}% ${run.summary!.overallSignal}. Probabilistic estimate — not investment advice. Demo data.`,
    prediction: run.prediction!,
    critic: run.critic!,
    analysis: run.summary!,
    sources: [
      { provider: "yfinance (demo)", url: "#", retrievedAt: isoDaysAgo(0) },
      { provider: "Company filings (demo)", url: "#", retrievedAt: isoDaysAgo(1) },
      { provider: "News providers (demo)", url: "#", retrievedAt: isoDaysAgo(0) },
    ],
  };
}
